interface MySqlSessionStateSeenThroughConnectorKnexClient {
  readonly currentUserAccount: string;
  readonly currentDatabaseName: string | null;
  readonly detectedServerFlavor: MySqlServerFlavor | undefined;
  /** '' when the session isn't encrypted. */
  readonly sslCipherName: string;
  /** '' when the session isn't encrypted. */
  readonly sslProtocolVersion: string;
  readonly sessionTimeZone: string;
  readonly sessionSqlMode: string;
  readonly sessionStatementTimeoutValue: number;
}

interface ShowStatusRow {
  Variable_name: string;
  Value: string;
}

/**
 * Open the connector's own knex client (built from the same `parseStoredMySqlCredentials` output production uses)
 * and read the session it set up. The pool holds one connection, so every query runs on the connection whose
 * `afterCreate` applied the session settings.
 */
async function readSessionStateThroughConnectorKnexClient(
  decryptedCredentials: DecryptedCredentials,
  statementTimeoutSessionVariableName: 'max_execution_time' | 'max_statement_time',
): Promise<MySqlSessionStateSeenThroughConnectorKnexClient> {
  const connectorKnexClient = new KnexMySqlClient(parseStoredMySqlCredentials(decryptedCredentials));
  try {
    const connectionTestResult = await connectorKnexClient.testQuery();
    const [sslCipherRows] = (await connectorKnexClient.knex.raw("SHOW SESSION STATUS LIKE 'Ssl_cipher'")) as [
      ShowStatusRow[],
      unknown,
    ];
    const [sslVersionRows] = (await connectorKnexClient.knex.raw("SHOW SESSION STATUS LIKE 'Ssl_version'")) as [
      ShowStatusRow[],
      unknown,
    ];
    // The variable name is one of two constants from the flavor fixture, never user input.
    const [sessionVariableRows] = (await connectorKnexClient.knex.raw(
      `SELECT CURRENT_USER() AS current_user_account, @@SESSION.time_zone AS session_time_zone,
              @@SESSION.sql_mode AS session_sql_mode,
              @@SESSION.${statementTimeoutSessionVariableName} AS session_statement_timeout`,
    )) as [
      {
        current_user_account: string;
        session_time_zone: string;
        session_sql_mode: string;
        session_statement_timeout: string | number;
      }[],
      unknown,
    ];
    const sessionVariables = sessionVariableRows[0];
    return {
      currentUserAccount: sessionVariables.current_user_account,
      currentDatabaseName: connectionTestResult.currentDatabaseName,
      detectedServerFlavor: connectorKnexClient.detectedServerFlavor,
      sslCipherName: sslCipherRows[0]?.Value ?? '',
      sslProtocolVersion: sslVersionRows[0]?.Value ?? '',
      sessionTimeZone: sessionVariables.session_time_zone,
      sessionSqlMode: sessionVariables.session_sql_mode,
      sessionStatementTimeoutValue: Number(sessionVariables.session_statement_timeout),
    };
  } finally {
    await connectorKnexClient.dispose();
  }
}

/** The production path: registry `createConnector` (stored-credential re-validation included), then `testConnection`. */
async function connectThroughConnectorBuiltByRegistry(decryptedCredentials: DecryptedCredentials): Promise<void> {
  // Every connector operation disposes its own short-lived client, so there is nothing to disconnect afterwards.
  const connector = await createMySqlConnectorThroughRegistryForIntegrationTest(decryptedCredentials);
  await connector.testConnection();
}

async function captureErrorThrownByOperation(operation: () => Promise<unknown>): Promise<unknown> {
  try {
    await operation();
  } catch (error) {
    return error;
  }
  throw new Error('Expected the operation to fail, but it succeeded');
}

/** What the connection service does when `testConnection` throws: map the raw error through the connector. */
async function describeTestConnectionFailureLikeTheConnectionService(
  decryptedCredentials: DecryptedCredentials,
): Promise<{ rawErrorThrownByTestConnection: unknown; userFacingErrorDetails: ConnectorErrorDetails }> {
  const connector = await createMySqlConnectorThroughRegistryForIntegrationTest(decryptedCredentials);
  const rawErrorThrownByTestConnection = await captureErrorThrownByOperation(() => connector.testConnection());
  return {
    rawErrorThrownByTestConnection,
    userFacingErrorDetails: connector.extractConnectorErrorDetails(rawErrorThrownByTestConnection),
  };
}

