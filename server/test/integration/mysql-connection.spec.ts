/**
 * MySQL connector: connection, TLS, authentication-plugin and connection-error integration tests (DEV-12035).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * What this validates that the unit tests don't
 * ═══════════════════════════════════════════════════════════════════════════
 * The unit specs check the mysql2 option object, the session-setup statements and the error mapper against fakes.
 * This spec connects to real MySQL 8.4 and MariaDB 11.4 servers, through the connector exactly as production builds
 * it (registry `createConnector` → stored-credential re-validation → knex client → mysql2), and proves:
 *
 *   1. Every SSL Mode behaves as MySQL's own `--ssl-mode`: REQUIRED and VERIFY_CA really encrypt, DISABLED really
 *      doesn't, VERIFY_CA rejects an untrusted server certificate, and VERIFY_IDENTITY really checks the hostname.
 *   2. The per-connection session setup runs on the live connection: UTC time zone, the exact SQL mode (no
 *      NO_BACKSLASH_ESCAPES / ANSI_QUOTES) and the flavor's statement-timeout variable.
 *   3. Both password plugins mysql2 supports work, including caching_sha2_password's plaintext RSA path, and a
 *      password full of URL metacharacters survives (no URL is ever built from the fields).
 *   4. Real connect-phase failures (1045, 1044, 1049, refused ports, TLS failures, unsupported plugins) become the
 *      mapper's fixed sentences, naming at most the host the user typed — never a resolved IP or SQL.
 *   5. The credential boundary: a connection string is decomposed into discrete keys and never stored; a stored blob
 *      holding a connection string is refused at connect time; VERIFY_IDENTITY with an IP host is refused.
 *   6. Deployed environments go through the database host guard: with RUNNING_IN_CLOUD=true the same server, on a
 *      loopback or Docker-network address, is refused with the generic not-reachable message (DEV-12390).
 *
 * This spec creates no tables (only `scratch_mysql_it_conn_*` users, dropped before and after the run). It
 * deliberately does NOT call `dropAllMySqlIntegrationTables`: that would drop other MySQL specs' tables.
 *
 * Run (local servers: server/localdev/docker-compose.mysql.yml):
 *   cd server && MYSQL_TEST_URL=mysql://test:test@127.0.0.1:3306/test_db \
 *     MYSQL_TEST_ROOT_URL=mysql://root:root@127.0.0.1:3306/test_db \
 *     MARIADB_TEST_URL=mysql://test:test@127.0.0.1:3307/test_db \
 *     MARIADB_TEST_ROOT_URL=mysql://root:root@127.0.0.1:3307/test_db \
 *     yarn test:integration test/integration/mysql-connection --runInBand
 */
