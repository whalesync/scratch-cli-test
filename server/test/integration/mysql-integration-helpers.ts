/**
 * Shared harness for the MySQL connector integration specs (`mysql-*.spec.ts`). Not a spec itself.
 *
 * The specs run against real MySQL 8.4 and MariaDB 11.4 servers: locally `server/localdev/docker-compose.mysql.yml`,
 * in CI the `integration test server mysql` job's sidecars. Each flavor is configured by a pair of URLs:
 *   - `*_TEST_URL`       the application user the connector connects as (scoped to `test_db`);
 *   - `*_TEST_ROOT_URL`  an admin connection the specs use to create hermetic `scratch_mysql_it_*` tables and
 *                        auth-plugin users, and (MySQL only) to read the server's auto-generated CA certificate.
 * A flavor whose URLs are unset is skipped, so the main integration job and the post-deploy environment tests
 * (which have no MySQL sidecars) skip every MySQL suite. The dedicated CI job sets
 * `MYSQL_INTEGRATION_FAIL_IF_UNCONFIGURED=true`, so a misconfigured job fails instead of passing green.
 *
 * The admin connection is test-only code, so it may use a URL; the connector itself never does.
 */
import { type DecryptedCredentials } from '@spinner/shared-types';
import mysql2Promise from 'mysql2/promise';
import { type Connector } from 'src/remote-service/connectors/connector';
import { connectorRegistry } from 'src/remote-service/connectors/connector-registry';
import 'src/remote-service/connectors/library';
import { SCRATCH_PRODUCTION_EGRESS_IP_ADDRESS } from 'src/remote-service/connectors/library/mysql/mysql-error-mapping';
import { Service } from 'src/remote-service/connectors/service-constants';
import { type JsonSafeObject } from 'src/utils/objects';

export type MySqlIntegrationFlavorName = 'mysql' | 'mariadb';

export interface MySqlIntegrationServerAddress {
  readonly host: string;
  readonly port: number;
  readonly databaseName: string;
  readonly username: string;
  readonly password: string;
}

export interface MySqlIntegrationFlavor {
  readonly flavorName: MySqlIntegrationFlavorName;
  /** The raw app-user URL, for AuthParser connection-string tests only. */
  readonly applicationUserTestUrl: string;
  readonly applicationUserServerAddress: MySqlIntegrationServerAddress;
  readonly rootUserServerAddress: MySqlIntegrationServerAddress;
  /** MariaDB has no caching_sha2_password plugin. */
  readonly serverSupportsCachingSha2PasswordPlugin: boolean;
  /** MySQL writes its auto-generated CA to the data directory (readable via LOAD_FILE); MariaDB 11.4's is in memory. */
  readonly serverWritesAutoGeneratedCaCertificateToDataDirectory: boolean;
  /** MariaDB's JSON is a LONGTEXT alias with a json_valid CHECK. */
  readonly serverStoresJsonColumnsAsLongtextAlias: boolean;
  readonly statementTimeoutSessionVariableName: 'max_execution_time' | 'max_statement_time';
}

/** Every table / user a spec creates starts with this, so cleanup can find (only) them. */
export const MYSQL_INTEGRATION_IDENTIFIER_PREFIX = 'scratch_mysql_it_';

const MYSQL_INTEGRATION_FLAVOR_ENVIRONMENT_VARIABLES: readonly {
  flavorName: MySqlIntegrationFlavorName;
  applicationUserUrlVariable: string;
  rootUserUrlVariable: string;
}[] = [
  { flavorName: 'mysql', applicationUserUrlVariable: 'MYSQL_TEST_URL', rootUserUrlVariable: 'MYSQL_TEST_ROOT_URL' },
  {
    flavorName: 'mariadb',
    applicationUserUrlVariable: 'MARIADB_TEST_URL',
    rootUserUrlVariable: 'MARIADB_TEST_ROOT_URL',
  },
];

function readTrimmedEnvironmentVariable(variableName: string): string | undefined {
  const value = process.env[variableName]?.trim();
  return value ? value : undefined;
}

/** `mysql://user:pass@host:port/db` → discrete parts (percent-decoded, default port 3306). */
export function parseMySqlIntegrationTestUrl(
  testUrl: string,
  environmentVariableName: string,
): MySqlIntegrationServerAddress {
  let parsedUrl: URL;
  try {
    parsedUrl = new URL(testUrl);
  } catch {
    throw new Error(`${environmentVariableName} is not a valid mysql:// URL`);
  }
  const databaseName = decodeURIComponent(parsedUrl.pathname.replace(/^\//, ''));
  if (!parsedUrl.hostname || !parsedUrl.username || !databaseName) {
    throw new Error(`${environmentVariableName} must look like mysql://user:password@host:port/database`);
  }
  return {
    host: parsedUrl.hostname,
    port: parsedUrl.port ? Number(parsedUrl.port) : 3306,
    databaseName,
    username: decodeURIComponent(parsedUrl.username),
    password: decodeURIComponent(parsedUrl.password),
  };
}

/** The flavors whose URL pairs are configured. Throws on a half-configured pair, or when the CI job demands both. */
export function listConfiguredMySqlIntegrationFlavors(): MySqlIntegrationFlavor[] {
  const configuredFlavors: MySqlIntegrationFlavor[] = [];
  const unconfiguredFlavorNames: MySqlIntegrationFlavorName[] = [];
  for (const {
    flavorName,
    applicationUserUrlVariable,
    rootUserUrlVariable,
  } of MYSQL_INTEGRATION_FLAVOR_ENVIRONMENT_VARIABLES) {
    const applicationUserTestUrl = readTrimmedEnvironmentVariable(applicationUserUrlVariable);
    const rootUserTestUrl = readTrimmedEnvironmentVariable(rootUserUrlVariable);
    if (!applicationUserTestUrl && !rootUserTestUrl) {
      unconfiguredFlavorNames.push(flavorName);
      continue;
    }
    if (!applicationUserTestUrl || !rootUserTestUrl) {
      throw new Error(`Set both ${applicationUserUrlVariable} and ${rootUserUrlVariable} (or neither)`);
    }
    configuredFlavors.push({
      flavorName,
      applicationUserTestUrl,
      applicationUserServerAddress: parseMySqlIntegrationTestUrl(applicationUserTestUrl, applicationUserUrlVariable),
      rootUserServerAddress: parseMySqlIntegrationTestUrl(rootUserTestUrl, rootUserUrlVariable),
      serverSupportsCachingSha2PasswordPlugin: flavorName === 'mysql',
      serverWritesAutoGeneratedCaCertificateToDataDirectory: flavorName === 'mysql',
      serverStoresJsonColumnsAsLongtextAlias: flavorName === 'mariadb',
      statementTimeoutSessionVariableName: flavorName === 'mysql' ? 'max_execution_time' : 'max_statement_time',
    });
  }
  if (process.env.MYSQL_INTEGRATION_FAIL_IF_UNCONFIGURED === 'true' && unconfiguredFlavorNames.length > 0) {
    throw new Error(
      `MYSQL_INTEGRATION_FAIL_IF_UNCONFIGURED is set but these flavors have no test URLs: ${unconfiguredFlavorNames.join(', ')}`,
    );
  }
  return configuredFlavors;
}

/**
 * `describe.each` over the configured flavors. With none configured, registers a skipped suite with one test
 * (Jest rejects `describe.each([])`, and a file with zero tests fails). Suite bodies must do I/O only in hooks.
 */
export function describeForEachConfiguredMySqlIntegrationFlavor(
  suiteTitle: string,
  defineSuiteForFlavor: (flavor: MySqlIntegrationFlavor) => void,
): void {
  const configuredFlavors = listConfiguredMySqlIntegrationFlavors();
  if (configuredFlavors.length === 0) {
    describe.skip(`${suiteTitle} (set MYSQL_TEST_URL / MARIADB_TEST_URL to run)`, () => {
      it('requires a configured MySQL or MariaDB test server', () => undefined);
    });
    return;
  }
  for (const flavor of configuredFlavors) {
    describe(`${suiteTitle} [${flavor.flavorName}]`, () => defineSuiteForFlavor(flavor));
  }
}

/** Discrete connector credentials for a server address (sslMode defaults to REQUIRED). */
export function buildMySqlConnectorCredentialsForIntegrationTest(
  address: MySqlIntegrationServerAddress,
  overrides: Partial<DecryptedCredentials> = {},
): DecryptedCredentials {
  return {
    databaseHost: address.host,
    databasePort: String(address.port),
    databaseName: address.databaseName,
    username: address.username,
    password: address.password,
    sslMode: 'REQUIRED',
    ...overrides,
  };
}

/** Build the connector exactly as production does: through the registry's `createConnector` (stored-credential re-validation included). */
export async function createMySqlConnectorThroughRegistryForIntegrationTest(
  decryptedCredentials: DecryptedCredentials,
): Promise<Connector<string, JsonSafeObject>> {
  const mysqlRegistration = connectorRegistry.get(Service.MYSQL);
  if (!mysqlRegistration) {
    throw new Error('The MySQL connector is not registered (library barrel import missing?)');
  }
  return mysqlRegistration.createConnector({
    connectorAccount: { id: 'coa_mysql_integration_test', authType: 'USER_PROVIDED_PARAMS', extras: null, version: 1 },
    decryptedCredentials,
    createOAuthAccessTokenProvider: () => {
      throw new Error('MySQL never uses OAuth');
    },
    createRateLimiter: () => undefined,
    getFolderOptionsByTableId: () => Promise.resolve(null),
    listFolderTableIds: () => Promise.resolve([]),
    isFeatureEnabled: () => Promise.resolve(false),
  });
}

/** A root connection for fixtures: TLS without verification, UTC session, strings for big numbers and dates. */
export async function openMySqlAdminConnection(
  rootUserServerAddress: MySqlIntegrationServerAddress,
): Promise<mysql2Promise.Connection> {
  const adminConnection = await mysql2Promise.createConnection({
    host: rootUserServerAddress.host,
    port: rootUserServerAddress.port,
    user: rootUserServerAddress.username,
    password: rootUserServerAddress.password,
    database: rootUserServerAddress.databaseName,
    ssl: { rejectUnauthorized: false },
    dateStrings: true,
    supportBigNumbers: true,
    bigNumberStrings: true,
    multipleStatements: false,
  });
  await adminConnection.query("SET SESSION time_zone = '+00:00'");
  return adminConnection;
}

/** Retry connect + `SELECT 1` (GitLab services don't wait for health; MySQL's first-boot init is slow). */
export async function waitForMySqlServerToAcceptConnections(
  address: MySqlIntegrationServerAddress,
  options: { timeoutMilliseconds?: number; retryIntervalMilliseconds?: number } = {},
): Promise<void> {
  const timeoutMilliseconds = options.timeoutMilliseconds ?? 90_000;
  const retryIntervalMilliseconds = options.retryIntervalMilliseconds ?? 1_000;
  const deadline = Date.now() + timeoutMilliseconds;
  let lastConnectionError: unknown;
  while (Date.now() < deadline) {
    try {
      const probeConnection = await openMySqlAdminConnection(address);
      await probeConnection.query('SELECT 1');
      await probeConnection.end();
      return;
    } catch (error) {
      lastConnectionError = error;
      await new Promise((resolve) => setTimeout(resolve, retryIntervalMilliseconds));
    }
  }
  const lastErrorDescription = lastConnectionError instanceof Error ? lastConnectionError.message : 'unknown error';
  throw new Error(
    `MySQL test server ${address.host}:${address.port} didn't accept connections within ${timeoutMilliseconds} ms ` +
      `(start server/localdev/docker-compose.mysql.yml): ${lastErrorDescription}`,
  );
}

/** Backtick-quote one identifier exactly as written (doubling embedded backticks) — never split on `.`. */
export function quoteMySqlIdentifierVerbatim(identifier: string): string {
  return `\`${identifier.replace(/`/g, '``')}\``;
}

/** Drop every `scratch_mysql_it_*` table and view in the database (FK checks off, so order doesn't matter). */
export async function dropAllMySqlIntegrationTables(
  adminConnection: mysql2Promise.Connection,
  databaseName: string,
): Promise<void> {
  const [integrationTables] = await adminConnection.query<mysql2Promise.RowDataPacket[]>(
    `SELECT TABLE_NAME AS table_name, TABLE_TYPE AS table_type FROM information_schema.TABLES
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME LIKE 'scratch\\_mysql\\_it\\_%'`,
    [databaseName],
  );
  await adminConnection.query('SET SESSION FOREIGN_KEY_CHECKS = 0');
  try {
    for (const integrationTable of integrationTables) {
      // Quote each name verbatim: mysql2's `??` splits on `.`, and integration tables deliberately have dotted names.
      const dropStatement = `${integrationTable.table_type === 'VIEW' ? 'DROP VIEW' : 'DROP TABLE'} IF EXISTS ${quoteMySqlIdentifierVerbatim(databaseName)}.${quoteMySqlIdentifierVerbatim(String(integrationTable.table_name))}`;
      await adminConnection.query(dropStatement);
    }
  } finally {
    await adminConnection.query('SET SESSION FOREIGN_KEY_CHECKS = 1');
  }
}

export async function dropMySqlIntegrationUsers(
  adminConnection: mysql2Promise.Connection,
  userNames: readonly string[],
): Promise<void> {
  for (const userName of userNames) {
    await adminConnection.query("DROP USER IF EXISTS ?@'%'", [userName]);
  }
}

/** MySQL only: the server's auto-generated CA (needs `--secure-file-priv=` so root may LOAD_FILE the data directory). */
export async function readAutoGeneratedMySqlServerCaCertificatePem(
  adminConnection: mysql2Promise.Connection,
): Promise<string> {
  const [caRows] = await adminConnection.query<mysql2Promise.RowDataPacket[]>(
    "SELECT LOAD_FILE(CONCAT(@@GLOBAL.datadir, 'ca.pem')) AS server_ca_certificate_pem",
  );
  const serverCaCertificatePem: unknown = caRows[0]?.server_ca_certificate_pem;
  if (serverCaCertificatePem === null || serverCaCertificatePem === undefined) {
    throw new Error(
      "Couldn't read the MySQL server CA: start mysqld with --secure-file-priv= (see server/localdev/docker-compose.mysql.yml)",
    );
  }
  return Buffer.isBuffer(serverCaCertificatePem)
    ? serverCaCertificatePem.toString('utf8')
    : String(serverCaCertificatePem);
}

/** A PEM pasted into a single-line `<input>` (newlines stripped) — what the web / desktop forms actually send. */
export function collapsePemToSingleLineLikeABrowserInputPaste(pem: string): string {
  return pem.replace(/\r?\n/g, '');
}

/** Assert a user-facing message carries no IP literal, raw network code or SQL. */
export function expectUserFacingErrorMessageToLeakNoNetworkOrSqlDetails(message: string): void {
  // Scratch's own published egress address is what users must allowlist, not a leak.
  const messageWithoutPublishedEgressAddress = message.replaceAll(SCRATCH_PRODUCTION_EGRESS_IP_ADDRESS, '');
  expect(messageWithoutPublishedEgressAddress).not.toMatch(/\b\d{1,3}(?:\.\d{1,3}){3}\b/);
  expect(message).not.toMatch(/\b(?:[0-9a-f]{1,4}:){3,7}[0-9a-f]{1,4}\b|::/i);
  expect(message).not.toMatch(/ECONNREFUSED|ETIMEDOUT|ENOTFOUND|EHOSTUNREACH/);
  // Compiled SQL always carries backtick-quoted identifiers; our own messages quote names with double quotes, so
  // "Can't delete from \"db\".\"t\"" doesn't trip this.
  expect(message).not.toMatch(
    /\b(?:select|insert|update|delete)\b[\s\S]*`[^`]+`[\s\S]*\b(?:from|into|set|where|values)\b/i,
  );
  expect(message).not.toMatch(/\b(?:from|into|update)\s+`[^`]+`/i);
}
