import { SUPABASE_SYSTEM_SCHEMAS } from '../pg-common';

/**
 * Extract the Supabase project ref from a connection string.
 *
 * Supports two formats:
 * - Pooler (Supavisor): username contains the ref, e.g. `postgres.PROJECT_REF`
 * - Direct: hostname contains the ref, e.g. `db.PROJECT_REF.supabase.co`
 */
export function extractProjectRef(connectionString: string): string {
  const url = new URL(connectionString);

  // Pooler format: username is `postgres.PROJECT_REF`
  const usernameParts = url.username.split('.');
  if (usernameParts.length >= 2) {
    return usernameParts.slice(1).join('.');
  }

  // Direct format: hostname is `db.PROJECT_REF.supabase.co`
  const hostParts = url.hostname.split('.');
  if (hostParts.length >= 3 && hostParts[0] === 'db') {
    return hostParts[1];
  }

  throw new Error(
    'Cannot extract project ref from connection string. Use the pooler (Supavisor) or direct connection format from your Supabase dashboard.',
  );
}

/** Root of every Supabase dashboard deep link, shared by the URL builders below. */
const SUPABASE_DASHBOARD_PROJECT_URL_PREFIX = 'https://supabase.com/dashboard/project';

/**
 * Whether a connection string points at Supabase's own cloud, as opposed to a
 * self-hosted Supabase or a plain Postgres reached through this connector.
 * Only cloud projects have a supabase.com dashboard to deep-link into, and a
 * ref extracted from some other host's connection string is meaningless there.
 */
export function isSupabaseCloudHostedConnectionString(connectionString: string): boolean {
  try {
    const { hostname } = new URL(connectionString);
    // `.supabase.com` covers the Supavisor pooler; `.supabase.co` the direct
    // `db.<ref>.supabase.co` host.
    return hostname.endsWith('.supabase.com') || hostname.endsWith('.supabase.co');
  } catch {
    return false;
  }
}

/**
 * Deep link to a SCHEMA in the Supabase dashboard's table editor — the editor
 * opened on that schema's table list. This is the right landing page for a
 * create destination: it is where the tables we create will appear.
 */
export function buildSupabaseSchemaEditorUrl(projectRef: string, schema: string): string {
  return `${SUPABASE_DASHBOARD_PROJECT_URL_PREFIX}/${projectRef}/editor?schema=${encodeURIComponent(schema)}`;
}

/**
 * Deep link to a relation in the Supabase dashboard's table editor. The editor
 * addresses a relation by its Postgres `pg_class` OID — the same id Supabase's
 * own pg-meta emits for a table (`c.oid :: int8 AS id`) — never by name, so the
 * caller has to resolve the OID from the catalog first. Same URL as
 * {@link buildSupabaseSchemaEditorUrl} with the relation appended.
 */
export function buildSupabaseTableEditorUrl(projectRef: string, schema: string, relationOid: number): string {
  return `${SUPABASE_DASHBOARD_PROJECT_URL_PREFIX}/${projectRef}/editor/${relationOid}?schema=${encodeURIComponent(schema)}`;
}

/**
 * Build the PL/pgSQL to create a service account role with permissions on all user schemas.
 */
export function buildCreateUserSQL(username: string, password: string): string {
  const excludedSchemas = [...SUPABASE_SYSTEM_SCHEMAS].map((s) => `'${s}'`).join(', ');
  // Note: username and password are generated by us (UUID-based), not user input
  return `
DO $$
DECLARE
  schema_record RECORD;
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${username}') THEN
    CREATE ROLE "${username}" LOGIN PASSWORD '${password}' BYPASSRLS;
  END IF;

  FOR schema_record IN
    SELECT schema_name FROM information_schema.schemata
    WHERE schema_name NOT IN (${excludedSchemas})
    AND schema_name NOT LIKE 'pg\\_%'
    AND schema_name NOT LIKE 'supabase\\_%'
  LOOP
    EXECUTE format('GRANT ALL ON SCHEMA %I TO "${username}"', schema_record.schema_name);
    EXECUTE format('GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA %I TO "${username}"', schema_record.schema_name);
    EXECUTE format('GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA %I TO "${username}"', schema_record.schema_name);
    EXECUTE format('GRANT ALL PRIVILEGES ON ALL FUNCTIONS IN SCHEMA %I TO "${username}"', schema_record.schema_name);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I GRANT ALL ON TABLES TO "${username}"', schema_record.schema_name);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I GRANT ALL ON SEQUENCES TO "${username}"', schema_record.schema_name);
    EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA %I GRANT ALL ON FUNCTIONS TO "${username}"', schema_record.schema_name);
  END LOOP;
END
$$;`;
}

/**
 * Build a connection string by replacing the username and password in the pooler URL.
 * Handles Supavisor shared-endpoint format where username includes project ref.
 */
export function buildConnectionString(
  poolerConnectionString: string,
  username: string,
  password: string,
  projectRef: string,
): string {
  try {
    const url = new URL(poolerConnectionString);
    // Supavisor shared endpoints use username format: user.projectRef
    if (url.username.includes('.')) {
      url.username = `${username}.${projectRef}`;
    } else {
      url.username = username;
    }
    url.password = encodeURIComponent(password);
    return url.toString();
  } catch {
    // Fallback: simple string replacement
    return poolerConnectionString
      .replace(/\/\/[^:]+:/, `//${username}:`)
      .replace(/:([^@]+)@/, `:${encodeURIComponent(password)}@`);
  }
}
