/**
 * Schema discovery for a Supabase project Scratch has no database role in yet.
 *
 * Browsing a project — listing its schemas and tables so the user can pick one —
 * must not, by itself, create anything inside that project (DEV-11875). So the
 * catalog queries behind the pickers run through the Management API's
 * `POST /projects/{ref}/database/query` endpoint, which executes SQL as the
 * project's own `postgres` user over the OAuth token we already hold. A real
 * Postgres login is provisioned only once a project is genuinely used
 * ({@link provisionServiceRoleForSupabaseProject}), and from that point on
 * discovery for that project runs over the connection instead — see
 * `SupabaseConnector.listTables`.
 *
 * The SQL is the same text {@link KnexPGClient} runs, imported from
 * `pg-common/pg-catalog-queries.ts` so the two paths can't drift; only the
 * execution differs (a rendered statement over HTTP, versus bound parameters
 * over the wire protocol).
 *
 * **What this path cannot do.** The view-addressability analysis
 * (`findViewsWithUniquelyAddressableColumns`) reads the Postgres wire protocol's
 * per-column row descriptor to trace a view's output columns back to their base
 * columns. A JSON HTTP response carries no such descriptor, so there is no
 * equivalent here and the connector simply omits that input for unprovisioned
 * projects: their views fall back to `requiresIdFieldSelection`, the same
 * supported path a genuinely unanalyzable view takes, so the user is asked to
 * name the ID column instead of us guessing. Once the project is provisioned,
 * full analysis resumes.
 */
import {
  buildFindAllSchemasQuery,
  buildFindAllTablesExcludingSchemasQuery,
  buildFindTablesWithAutoGeneratedPrimaryKeyQuery,
  buildFindTablesWithSingleColumnUniqueIndexQuery,
  renderBoundSqlStatementAsStandaloneSql,
  type BoundSqlStatement,
  type InformationSchemaCatalog,
  type TableName,
} from '../pg-common';
import { SupabaseApiClient } from './supabase-api-client';

export class SupabaseManagementApiCatalogReader {
  constructor(
    private readonly apiClient: SupabaseApiClient,
    private readonly projectRef: string,
  ) {}

  /** Mirrors `KnexPGClient.findAllSchemas`. */
  async findAllSchemas(): Promise<InformationSchemaCatalog[]> {
    return this.runCatalogQuery<InformationSchemaCatalog>(buildFindAllSchemasQuery());
  }

  /** Mirrors `KnexPGClient.findAllTablesExcludingSchemas`. */
  async findAllTablesExcludingSchemas(excludedSchemas: string[], excludePatterns?: string[]): Promise<TableName[]> {
    return this.runCatalogQuery<TableName>(buildFindAllTablesExcludingSchemasQuery(excludedSchemas, excludePatterns));
  }

  /** Mirrors `KnexPGClient.findTablesWithUniqueColumns`. */
  async findTablesWithUniqueColumns(excludedSchemas: string[]): Promise<Set<string>> {
    return this.runSchemaQualifiedTableNameQuery(buildFindTablesWithSingleColumnUniqueIndexQuery(excludedSchemas));
  }

  /** Mirrors `KnexPGClient.findTablesWithAutoGeneratedPK`. */
  async findTablesWithAutoGeneratedPK(excludedSchemas: string[]): Promise<Set<string>> {
    return this.runSchemaQualifiedTableNameQuery(buildFindTablesWithAutoGeneratedPrimaryKeyQuery(excludedSchemas));
  }

  private async runSchemaQualifiedTableNameQuery(statement: BoundSqlStatement): Promise<Set<string>> {
    const rows = await this.runCatalogQuery<{ table_schema: string; table_name: string }>(statement);
    return new Set(rows.map((row) => `${row.table_schema}.${row.table_name}`));
  }

  private async runCatalogQuery<TRow>(statement: BoundSqlStatement): Promise<TRow[]> {
    return this.apiClient.runSqlQuery<TRow>(this.projectRef, renderBoundSqlStatementAsStandaloneSql(statement));
  }
}
