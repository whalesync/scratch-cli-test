describe('SupabaseConnector pull duplicate-id guard for views (DEV-11136)', () => {
  let connector: SupabaseConnector;

  beforeEach(() => {
    jest.clearAllMocks();
    mockDispose.mockResolvedValue(undefined);
    connector = new SupabaseConnector({ connectionString: CONNECTION_STRING });
  });

  async function pullRows(rows: Record<string, unknown>[][]) {
    let call = 0;
    mockSelectAll.mockImplementation(() => Promise.resolve(rows[call++] ?? []));
    const pulled: Record<string, unknown>[] = [];
    await connector.pullRecordFiles(
      buildIncrementalTableSpec(),
      ({ files }) => {
        pulled.push(...files);
        return Promise.resolve();
      },
      {},
      {},
    );
    return pulled;
  }

  it('fails a view pull loudly when the id column repeats, even across batches', async () => {
    mockFindViewRelationOid.mockResolvedValue(4242);
    // A full first batch (READ_BATCH_SIZE = 500) keeps the pull loop fetching;
    // the duplicate id straddles the batch boundary.
    const fullFirstBatch = Array.from({ length: 500 }, (_, i) => ({ id: i }));
    const secondBatchRepeatingLastId = [{ id: 499 }, { id: 500 }];
    await expect(pullRows([fullFirstBatch, secondBatchRepeatingLastId])).rejects.toThrow(
      'returned multiple rows with the same "id" value (499)',
    );
  });

  it('passes a view pull whose id values are all distinct', async () => {
    mockFindViewRelationOid.mockResolvedValue(4242);
    const pulled = await pullRows([[{ id: 1 }, { id: 2 }, { id: 3 }]]);
    expect(pulled).toHaveLength(3);
  });

  it('skips the guard for base tables — index-backed uniqueness needs no runtime check', async () => {
    mockFindViewRelationOid.mockResolvedValue(null);
    const pulled = await pullRows([[{ id: 7 }, { id: 7 }]]);
    expect(pulled).toHaveLength(2);
  });
});

