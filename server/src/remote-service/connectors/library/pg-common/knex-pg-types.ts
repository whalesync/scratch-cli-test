/**
 * A column guaranteed unique by a single-column, non-partial, non-expression,
 * non-deferrable unique index (including a single-column primary key). These are
 * the only columns a record can safely be addressed by (`idPath`) and the only
 * columns a foreign key can reference — one column of a composite primary key is
 * NOT in this set, because it is not unique on its own.
 */
export interface SingleColumnUniqueIndexColumn {
  column_name: string;
  /** Exact native type via `format_type(atttypid, atttypmod)` — schema-qualified when off the search_path (e.g. `app.my_enum`, `citext`, `integer[]`, `character varying(20)`). */
  native_type: string;
  /** True when the unique index backing this column is the table's primary key. */
  is_primary_key: boolean;
}

/**
 * Pick the one column a table's records should be addressed by: a single-column
 * primary key first, then an auto-generated single-column-unique column, then
 * the first single-column-unique column. Returns null when the table has no
 * single-column unique index at all (e.g. only a composite primary key) — such a
 * table's rows cannot be uniquely identified by any one column, so matching
 * updates/deletes on one would hit every row sharing the value.
 *
 * Shared by `pickPrimaryKey` (the read side's `idPath`) and
 * `findTableUniquelyAddressableColumn` (the foreign-key reference target for
 * created tables) so a foreign key always references the exact column whose
 * values the sync pipeline writes into it.
 */
export function chooseUniquelyAddressableColumn(
  singleColumnUniqueIndexColumns: SingleColumnUniqueIndexColumn[],
  allColumnsInTable: InformationSchemaColumn[],
): { column: string; nativeType: string } | null {
  if (singleColumnUniqueIndexColumns.length === 0) {
    return null;
  }
  const singleColumnPrimaryKey = singleColumnUniqueIndexColumns.find((uniqueColumn) => uniqueColumn.is_primary_key);
  if (singleColumnPrimaryKey) {
    return { column: singleColumnPrimaryKey.column_name, nativeType: singleColumnPrimaryKey.native_type };
  }
  const informationSchemaColumnByName = new Map(allColumnsInTable.map((column) => [column.column_name, column]));
  const autoGeneratedUniqueColumn = singleColumnUniqueIndexColumns.find((uniqueColumn) => {
    const informationSchemaColumn = informationSchemaColumnByName.get(uniqueColumn.column_name);
    return informationSchemaColumn !== undefined && isGeneratedColumn(informationSchemaColumn);
  });
  const chosenUniqueColumn = autoGeneratedUniqueColumn ?? singleColumnUniqueIndexColumns[0];
  return { column: chosenUniqueColumn.column_name, nativeType: chosenUniqueColumn.native_type };
}

/**
 * Determines if a column has a generated/auto-incrementing default value.
 * Covers serial, gen_random_uuid(), now(), nanoid(), auth.uid(), and IDENTITY columns.
 */
export function isGeneratedColumn(column: InformationSchemaColumn): boolean {
  const d = column.column_default;
  if (d === null) {
    return column.is_identity === 'YES' && column.identity_increment !== null && column.identity_cycle === 'NO';
  }
  return (
    d.includes('nextval') || d.includes('gen') || d.includes('now') || d.includes('nanoid') || d.includes('auth.uid()')
  );
}

