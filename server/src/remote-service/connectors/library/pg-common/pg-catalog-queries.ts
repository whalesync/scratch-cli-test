/**
 * Catalog-discovery SQL shared by the two ways Scratch can reach a Postgres
 * database.
 *
 * The normal way is a real connection ({@link KnexPGClient}, which runs these
 * through `knex.raw(sql, bindings)`). Supabase has a second one: its Management
 * API's `POST /projects/{ref}/database/query` endpoint runs a SQL *string* as
 * the project's own superuser, which is how a Supabase project can be browsed
 * before Scratch has provisioned a login role in it (DEV-11875). That endpoint
 * takes no bind parameters, so the statement has to be rendered standalone —
 * see {@link renderBoundSqlStatementAsStandaloneSql}.
 *
 * Keeping the statements here rather than inline in `KnexPGClient` is what stops
 * the two paths from drifting: a fix to the table-listing predicate lands in one
 * place and both callers get it.
 *
 * Only the queries that return plain rows live here. The view-provenance probe
 * (`findViewsWithUniquelyAddressableColumns`) deliberately does not: it reads
 * the Postgres wire protocol's row *descriptor* (`tableID`/`columnID` per output
 * column), which a JSON HTTP endpoint cannot carry, so it is connection-only by
 * nature.
 */
import knex, { type Knex } from 'knex';

/** A SQL statement plus its positional (`?`) bindings, ready for either execution path. */
export interface BoundSqlStatement {
  sql: string;
  bindings: (string | number)[];
}

/**
 * A connection-less knex used solely as a SQL *formatter*. `toQuery()` applies
 * the pg dialect's own literal escaping to each binding, so rendering a
 * statement this way is exactly as safe as letting the driver bind it — and far
 * safer than hand-rolled string interpolation.
 */
let sqlFormattingKnexInstance: Knex | undefined;

function getSqlFormattingKnexInstance(): Knex {
  sqlFormattingKnexInstance ??= knex({ client: 'pg' });
  return sqlFormattingKnexInstance;
}

/**
 * Render a bound statement into a single standalone SQL string, for an executor
 * that accepts only SQL text (Supabase's Management API query endpoint).
 */
export function renderBoundSqlStatementAsStandaloneSql(statement: BoundSqlStatement): string {
  return getSqlFormattingKnexInstance().raw(statement.sql, statement.bindings).toQuery();
}

/** Every schema in the database (`information_schema.schemata`). */
export function buildFindAllSchemasQuery(): BoundSqlStatement {
  return { sql: 'SELECT catalog_name, schema_name FROM information_schema.schemata', bindings: [] };
}

/**
 * All tables and views outside the excluded schemas and LIKE patterns.
 * Materialized views are absent from `information_schema.tables` entirely, so
 * they're unioned in from `pg_class` (relkind 'm') with the synthetic table_type
 * 'MATERIALIZED VIEW' — mirroring how information_schema labels the other
 * relation kinds ('BASE TABLE', 'VIEW', 'FOREIGN').
 */
export function buildFindAllTablesExcludingSchemasQuery(
  excludedSchemas: string[],
  excludePatterns?: string[],
): BoundSqlStatement {
  const patterns = excludePatterns ?? [];
  const schemaPlaceholders = excludedSchemas.map(() => '?').join(', ');
  const informationSchemaPatternClauses = patterns.map(() => 'AND table_schema NOT LIKE ?').join('\n         ');
  const matviewPatternClauses = patterns.map(() => 'AND n.nspname NOT LIKE ?').join('\n         ');
  return {
    sql: `SELECT table_name, table_schema, table_type
       FROM information_schema.tables
       WHERE table_schema NOT IN (${schemaPlaceholders})
         ${informationSchemaPatternClauses}
       UNION ALL
       SELECT c.relname AS table_name, n.nspname AS table_schema, 'MATERIALIZED VIEW' AS table_type
       FROM pg_class c
       JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE c.relkind = 'm'
         AND n.nspname NOT IN (${schemaPlaceholders})
         ${matviewPatternClauses}`,
    bindings: [...excludedSchemas, ...patterns, ...excludedSchemas, ...patterns],
  };
}

/**
 * Tables whose primary key column has an auto-generated default
 * (serial/nextval, gen_random_uuid, now(), nanoid, auth.uid(), or IDENTITY).
 */
export function buildFindTablesWithAutoGeneratedPrimaryKeyQuery(excludedSchemas: string[]): BoundSqlStatement {
  return {
    sql: `SELECT DISTINCT n.nspname AS table_schema, c.relname AS table_name
       FROM pg_index i
       JOIN pg_class c ON c.oid = i.indrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace
       JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
       JOIN information_schema.columns isc
         ON isc.table_schema = n.nspname
        AND isc.table_name = c.relname
        AND isc.column_name = a.attname
       WHERE i.indisprimary
         AND n.nspname NOT IN (${excludedSchemas.map(() => '?').join(', ')})
         AND (
           isc.column_default LIKE '%nextval%'
           OR isc.column_default LIKE '%gen%'
           OR isc.column_default LIKE '%now%'
           OR isc.column_default LIKE '%nanoid%'
           OR isc.column_default LIKE '%auth.uid()%'
           OR (isc.is_identity = 'YES' AND isc.identity_increment IS NOT NULL AND isc.identity_cycle = 'NO')
         )`,
    bindings: excludedSchemas,
  };
}

/**
 * Tables with at least one genuinely unique single column — a single-column,
 * non-partial, non-expression, non-deferrable unique index (which includes a
 * single-column primary key). A composite primary key does NOT qualify
 * (DEV-10802).
 */
export function buildFindTablesWithSingleColumnUniqueIndexQuery(excludedSchemas: string[]): BoundSqlStatement {
  return {
    sql: `SELECT DISTINCT n.nspname AS table_schema, c.relname AS table_name
       FROM pg_index i
       JOIN pg_class c ON c.oid = i.indrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE i.indisunique
         AND array_length(i.indkey, 1) = 1
         AND i.indkey[0] <> 0
         AND i.indpred IS NULL
         AND i.indimmediate
         AND n.nspname NOT IN (${excludedSchemas.map(() => '?').join(', ')})`,
    bindings: excludedSchemas,
  };
}
