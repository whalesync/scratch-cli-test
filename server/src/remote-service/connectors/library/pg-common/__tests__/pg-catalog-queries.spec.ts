import {
  buildFindAllSchemasQuery,
  buildFindAllTablesExcludingSchemasQuery,
  buildFindTablesWithAutoGeneratedPrimaryKeyQuery,
  buildFindTablesWithSingleColumnUniqueIndexQuery,
  renderBoundSqlStatementAsStandaloneSql,
} from '../pg-catalog-queries';

describe('pg catalog queries', () => {
  it('emits one placeholder per excluded schema and pattern, in the order the bindings are listed', () => {
    const statement = buildFindAllTablesExcludingSchemasQuery(['auth', 'storage'], ['pg\\_%']);

    // The schema list appears twice (information_schema.tables, then the
    // matview union), so the bindings repeat in the same order.
    expect(statement.bindings).toEqual(['auth', 'storage', 'pg\\_%', 'auth', 'storage', 'pg\\_%']);
    expect(statement.sql.match(/\?/g)).toHaveLength(statement.bindings.length);
  });

  it('carries no bindings for the parameterless schema listing', () => {
    expect(buildFindAllSchemasQuery().bindings).toEqual([]);
  });

  describe('renderBoundSqlStatementAsStandaloneSql', () => {
    it('inlines every binding, leaving no placeholder for an executor that cannot bind', () => {
      const rendered = renderBoundSqlStatementAsStandaloneSql(
        buildFindTablesWithSingleColumnUniqueIndexQuery(['auth', 'storage']),
      );

      expect(rendered).not.toContain('?');
      expect(rendered).toContain("'auth'");
      expect(rendered).toContain("'storage'");
    });

    it('escapes a quote in a binding rather than closing the literal (this SQL is executed as text)', () => {
      const rendered = renderBoundSqlStatementAsStandaloneSql(
        buildFindTablesWithAutoGeneratedPrimaryKeyQuery(["o'brien"]),
      );

      expect(rendered).toContain("'o''brien'");
    });

    it('preserves a LIKE escape sequence, as an E-string with the backslash doubled', () => {
      const rendered = renderBoundSqlStatementAsStandaloneSql(
        buildFindAllTablesExcludingSchemasQuery(['auth'], ['supabase\\_%']),
      );

      // `E'supabase\\_%'` is the same value the driver would have bound: the
      // E-string collapses `\\` back to one backslash, so LIKE still sees the
      // escaped underscore rather than a wildcard.
      expect(rendered).toContain("E'supabase\\\\_%'");
    });
  });
});
